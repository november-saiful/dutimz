// Derives the deployment's asset version from the content of the two files every
// page loads: the stylesheet and the client bundle's source. Hashing the sources
// (rather than dist outputs) lets the version exist before `astro build` renders
// any HTML, so one `prebuild` step is enough.
//
// Every page then references /site.css?v=<hash> and /client.js?v=<hash>. A new
// deploy changes the hash, the URLs change, and no browser or Cloudflare edge
// cache — including per-hostname caches on dutimz.com and www.dutimz.com — can
// pair fresh markup with yesterday's stylesheet or bundle again.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const inputs = ['public/site.css', 'src/scripts/client.ts'];
const hash = createHash('sha256');
for (const path of inputs) {
  hash.update(path);
  hash.update(await readFile(path));
}
const version = hash.digest('hex').slice(0, 16);
const module = `// Generated by scripts/write-asset-version.mjs — do not edit by hand.
// Committed so typecheck and CI builds compile before regeneration runs; every
// \`npm run build\` rewrites it. The value changes whenever site.css or the client
// sources change, which is what makes each deployment's asset URLs unique.
export const ASSET_VERSION = '${version}';
export const siteCssHref = \`/site.css?v=\${ASSET_VERSION}\`;
export const clientJsSrc = \`/client.js?v=\${ASSET_VERSION}\`;
`;
await mkdir('src/generated', { recursive: true });
await writeFile('src/generated/asset-version.ts', module);
console.log(`asset version ${version}`);
