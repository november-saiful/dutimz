const BN_DIGITS = "০১২৩৪৫৬৭৮৯";

/**
 * A year as Bengali digits, e.g. 2024 → "২০২৪". `bn()` cannot do this: the bn-BD number
 * formatter inserts its lakh/crore group separators, so bn(2024) reads "২,০২৪".
 */
function bnYear(year: number): string {
  return String(year).replace(/[0-9]/g, (digit) => BN_DIGITS[Number(digit)]);
}

// The oldest session a member could still be describing; raise this if an older alumni year
// ever needs to appear. The newest entry is the session that started this July, so the list
// ends one academic year ahead of the calendar year.
const SESSION_FIRST_YEAR = 2000;

/**
 * Session labels like "২০২৪-২৫", newest first, from ২০০০-০১ up to the current academic year.
 * Computed at build time, so each deploy refreshes the top of the list.
 */
export const DU_SESSIONS: string[] = Array.from(
  { length: new Date().getFullYear() + 1 - SESSION_FIRST_YEAR },
  (_, index) => {
    const start = SESSION_FIRST_YEAR + index;
    const end = String(start + 1).slice(-2);
    return `${bnYear(start)}-${bnYear(Number(end))}`;
  },
).reverse();
